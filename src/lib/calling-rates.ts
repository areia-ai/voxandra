export function getDestinationCountryForPrefix(value: string) {
  for (const [prefix, country] of DESTINATION_COUNTRY_PREFIXES) {
    if (value.startsWith(prefix)) return country;
  }
  return "unknown";
}

export function getRetailRateCentsPerMinute(destinationCountry: string | undefined | null) {
  if (!destinationCountry || destinationCountry === "unknown") return null;
  return RETAIL_RATE_CENTS_PER_MINUTE[destinationCountry] ?? DEFAULT_RETAIL_RATE_CENTS_PER_MINUTE;
}

// Every route to this destination is refused at quote time, so it must not be
// shown with a price. Before the card covered all allowed countries these fell
// through to the flat default, which advertised 35c/min for a call that could
// never be placed.
export function isDestinationCountryUnavailable(destinationCountry: string | undefined | null) {
  if (!destinationCountry || destinationCountry === "unknown") return false;
  return UNAVAILABLE_DESTINATION_COUNTRIES.includes(destinationCountry);
}

// The priciest quotable route in a country, for display beside the cheapest.
// Falls back to the cheapest so a country with no range shows a single price.
export function getRetailRateMaxCentsPerMinute(destinationCountry: string | undefined | null) {
  if (!destinationCountry || destinationCountry === "unknown") return null;
  return (
    RETAIL_RATE_MAX_CENTS_PER_MINUTE[destinationCountry] ??
    getRetailRateCentsPerMinute(destinationCountry)
  );
}

export function formatRateCentsPerMinute(rateCentsPerMinute?: number | null) {
  if (!rateCentsPerMinute) return "";
  return `$${(rateCentsPerMinute / 100).toFixed(2)}/min`;
}

// Landline and mobile in the same country can differ by more than an order of
// magnitude (Portugal: 1.71c vs 49.5c provider cost), so one number cannot
// honestly describe a destination. Quoting only the cheap end would advertise a
// landline price for a mobile call.
export function formatRateRangeCentsPerMinute(
  fromCentsPerMinute?: number | null,
  toCentsPerMinute?: number | null
) {
  if (!fromCentsPerMinute) return "";
  if (!toCentsPerMinute || toCentsPerMinute <= fromCentsPerMinute) {
    return formatRateCentsPerMinute(fromCentsPerMinute);
  }
  return `$${(fromCentsPerMinute / 100).toFixed(2)}-$${(toCentsPerMinute / 100).toFixed(2)}/min`;
}

export function destinationRouteLabel(destinationCountry: string | undefined | null) {
  if (!destinationCountry || destinationCountry === "unknown") return "Selected destination";
  return DESTINATION_ROUTE_LABELS[destinationCountry] ?? destinationCountry;
}

export function getDialerRoutePricing(countryCode: string) {
  const destinationCountry = getDestinationCountryForPrefix(countryCode);
  const unavailable = isDestinationCountryUnavailable(destinationCountry);

  return {
    destinationCountry,
    routeLabel: destinationRouteLabel(destinationCountry),
    rateCentsPerMinute: unavailable ? null : getRetailRateCentsPerMinute(destinationCountry),
    maxRateCentsPerMinute: unavailable ? null : getRetailRateMaxCentsPerMinute(destinationCountry),
    unavailable,
  };
}

export function compactDialerCountryLabel(code: string, label: string) {
  const flag = label.trim().split(/\s+/)[0] ?? "";
  return `${flag} ${code}`.trim();
}

export function dialerCountryLabel(code: string) {
  return dialerCountries.find(([countryCode]) => countryCode === code)?.[1] ?? code;
}


// Best-effort locale-based default; returns null when it can't be determined
// (server render, unsupported browser, or an unrecognized region) so callers
// can fall back to a fixed, SSR-safe default instead.
export function inferDialCodeFromLocale(): string | null {
  if (typeof navigator === "undefined") return null;
  try {
    const region = new Intl.Locale(navigator.language).maximize().region;
    return region ? (REGION_TO_DIAL_CODE[region] ?? null) : null;
  } catch {
    return null;
  }
}
